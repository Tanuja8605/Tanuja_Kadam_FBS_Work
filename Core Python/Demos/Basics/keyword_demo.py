####Data Types

### Numeric data type

# 1.int
a = 10
print(type(a))
# 3.float
a = 2.4
print(type(a))
# 2.complex = real + imaginary
a = 5 + 4j
print(type(a))

### Text

#string
a = 'firstbit solutions'
a = "Data science and IT technologie's"
print(type(a))

### Sequential data type

#  1.list
l = [10,20,30,40]
print(type(l))

# 2.Tuple
tt = (10,20,30,40)
print(type(tt))

# 3.Range
x = range(1,10)
print(type(x))

### Set Type

# 1.Set
s = {10,20,30,40}
print(type(s))

# 2.FrozenSet

fs = frozenset({10,20,30,40})
print(type(fs))

### Mapping
# 1.dict
x = {1:'Python',2:'Java',3:'C'}
print(type(x))

### Other
# 1.Boolean
x = False
x = True
print(type(x))

# 2.Nonetype
x = None
print(type(x))






